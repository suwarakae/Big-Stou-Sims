export type StudentStatus = 
  | 'กำลังศึกษา' 
  | 'สำเร็จการศึกษา' 
  | 'พักการเรียน' 
  | 'รักษาสถานภาพ' 
  | 'พ้นสภาพการเป็นนักศึกษา';

export interface Student {
  id: string; // unique ID
  studentId: string; // 10 digits มสธ. e.g. "6630014523"
  title: 'นาย' | 'นาง' | 'นางสาว' | 'ว่าที่ ร.ต.' | 'ดร.' | 'อื่นๆ';
  firstName: string;
  lastName: string;
  faculty: string; // สาขาวิชา
  major: string; // แขนงวิชา/วิชาเอก
  stouCenter: string; // ศูนย์วิทยบริการและชุมชนสัมพันธ์
  academicYear: number; // ปีที่เข้าศึกษา พ.ศ. เช่น 2566, 2567
  entrySemester: 1 | 2; // ภาคการศึกษา
  phone: string; // 10 digits
  email: string;
  lineId?: string;
  idCardNumber?: string; // เลขบัตรประชาชน 13 หลัก (ทางเลือก)
  address: string; // ที่อยู่
  subdistrict: string; // แขวง/ตำบล
  district: string; // เขต/อำเภอ
  province: string; // จังหวัด
  postalCode: string; // รหัสไปรษณีย์ 5 หลัก
  status: StudentStatus;
  gpa?: number; // ผลการเรียนเฉลี่ย
  createdAt: string; // ISO string
  updatedAt: string; // ISO string
  notes?: string; // บันทึกเพิ่มเติม
}

export interface StudentFilterOptions {
  searchQuery: string;
  faculty: string;
  status: string;
  stouCenter: string;
  academicYear: string;
}

export interface ValidationError {
  field: keyof Student | string;
  message: string;
}

